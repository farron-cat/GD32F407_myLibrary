// 获取热敏电阻温度值
int8_t bsp_ntc_get_tem(void)
{
    uint16_t adc_dat = 0;
    float vol = 0.0;
    float r = 0.0;
    int8_t tem = 0;
    // NTC热敏电阻
    adc_dat = NTC_GET_ENCODE();
    // adc基准电压/参考电压2.5V
    vol = adc_dat * VREF / 4096;

    //(3.3-vol)/10 = vol/Rx
    r = 10 * vol / (3.3 - vol);
    // 通过电阻查表得到温度值
    tem = search_tem((uint16_t)(r * 100));
    return tem;
}